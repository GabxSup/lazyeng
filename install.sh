#!/usr/bin/env bash
# install.sh — install LazyEng rules into an agent's instruction file.
#
#   ./install.sh                          # AGENTS.md in the current directory
#   ./install.sh --target claude          # CLAUDE.md
#   ./install.sh --target cursor --dry-run
#   ./install.sh --target claude --scope global
#   ./install.sh --target all             # every project-scope target
#   ./install.sh --target claude --uninstall
#   ./install.sh --list
#
# Two kinds of target:
#   shared  merges into a file you may already own (AGENTS.md, CLAUDE.md, ...)
#           using <!-- lazyeng:begin --> ... <!-- lazyeng:end --> markers, so
#           your own instructions survive and uninstall is clean.
#   owned   a dedicated file that LazyEng owns outright (.mdc, SKILL.md, ...).
#
# Requires: bash 3.2+, awk, cmp, mktemp. No network.

set -euo pipefail

ROOT=$(cd "$(dirname "$0")" && pwd)
VERSION=$(tr -d '[:space:]' < "$ROOT/VERSION" 2>/dev/null || echo unknown)
DIST=$ROOT/dist

BEGIN_MARK='<!-- lazyeng:begin -->'
END_MARK='<!-- lazyeng:end -->'
OWNED_MARK='Generated by build.sh from core'

TARGET=
SCOPE=project
DIR=.
DRY=0
UNINSTALL=0
FORCE=0
LIST=0

usage() {
    cat <<'END'
Usage: install.sh [OPTIONS]

Installs LazyEng rules into an AI agent's instruction file.

Options:
  -t, --target NAME   which agent (default: agents). See --list.
                      Use "all" for every project-scope target.
  -s, --scope SCOPE   "project" (default) or "global" (your home dir)
  -d, --dir PATH      project root to install into (default: .)
      --uninstall     remove what this script installed
      --dry-run       show what would change, write nothing
  -f, --force         overwrite a file LazyEng does not manage
  -l, --list          list targets and the path each installs to
  -h, --help          show this help
  -V, --version       show version

Targets: agents claude claude-skill gemini copilot copilot-instructions junie amazonq cursor windsurf cline aider

Examples:
  ./install.sh --target claude
  ./install.sh --target cursor --dir ~/code/myapp --dry-run
  ./install.sh --target all --uninstall
END
}

die()   { printf 'install.sh: %s\n' "$*" >&2; exit 1; }
usage_error() { printf 'install.sh: %s (try --help)\n' "$*" >&2; exit 2; }
say() { printf '%s\n' "$*"; }
act() { if [ "$DRY" = 1 ]; then say "would $*"; else say "$*"; fi; }

while [ $# -gt 0 ]; do
    case $1 in
        -t|--target)    [ $# -ge 2 ] || usage_error "$1 needs a value"; TARGET=$2; shift 2 ;;
        -s|--scope)     [ $# -ge 2 ] || usage_error "$1 needs a value"; SCOPE=$2; shift 2 ;;
        -d|--dir)       [ $# -ge 2 ] || usage_error "$1 needs a value"; DIR=$2; shift 2 ;;
        --uninstall)    UNINSTALL=1; shift ;;
        --dry-run)      DRY=1; shift ;;
        -f|--force)     FORCE=1; shift ;;
        -l|--list)      LIST=1; shift ;;
        -h|--help)      usage; exit 0 ;;
        -V|--version)   echo "install.sh $VERSION"; exit 0 ;;
        *)              usage_error "unknown argument: $1" ;;
    esac
done

[ "$SCOPE" = project ] || [ "$SCOPE" = global ] || usage_error "scope must be project or global"

# Human-readable path for the resolved target, used by --list and messages.
describe() {
    case $1 in
        agents)              echo "AGENTS.md — Codex, Cursor, Muse, opencode, Zed, Amp, Jules, Junie (fallback), Antigravity, Copilot, Gemini CLI" ;;
        claude)              echo "CLAUDE.md — Claude Code" ;;
        claude-skill)        echo ".claude/skills/lazyeng/SKILL.md — Claude Code skill (Agent Skills standard)" ;;
        gemini)              echo "GEMINI.md — Gemini CLI / Antigravity (native name)" ;;
        copilot)             echo ".github/copilot-instructions.md — GitHub Copilot (global repo instructions)" ;;
        copilot-instructions)echo ".github/instructions/lazyeng.instructions.md — GitHub Copilot (modular, path-scoped)" ;;
        junie)               echo ".junie/AGENTS.md — JetBrains Junie" ;;
        amazonq)             echo ".amazonq/rules/lazyeng.md — Amazon Q Developer" ;;
        cursor)              echo ".cursor/rules/lazyeng.mdc — Cursor project rule" ;;
        windsurf)            echo ".windsurf/rules/lazyeng.md — Windsurf rule" ;;
        cline)               echo ".clinerules/lazyeng.md — Cline rule" ;;
        aider)               echo "CONVENTIONS.md — Aider" ;;
        *)            return 1 ;;
    esac
}

[ -n "$TARGET" ] || TARGET=agents

# resolve <target> <scope> — sets SRC, DEST, MODE (shared|owned).
# Returns non-zero if the target or the scope is unsupported.
resolve() {
    _t=$1; _s=$2
    case $_t in
        agents)              SRC=$DIST/AGENTS.md;                        MODE=shared; _p=AGENTS.md ;;
        claude)              SRC=$DIST/CLAUDE.md;                        MODE=shared; _p=CLAUDE.md ;;
        gemini)              SRC=$DIST/GEMINI.md;                        MODE=shared; _p=GEMINI.md ;;
        copilot)             SRC=$DIST/copilot-instructions.md;          MODE=shared; _p=.github/copilot-instructions.md ;;
        copilot-instructions)SRC=$DIST/copilot/lazyeng.instructions.md; MODE=owned;  _p=.github/instructions/lazyeng.instructions.md ;;
        aider)               SRC=$DIST/CONVENTIONS.md;                   MODE=shared; _p=CONVENTIONS.md ;;
        junie)               SRC=$DIST/junie/AGENTS.md;                  MODE=owned;  _p=.junie/AGENTS.md ;;
        amazonq)             SRC=$DIST/amazonq/lazyeng.md;               MODE=owned;  _p=.amazonq/rules/lazyeng.md ;;
        cursor)              SRC=$DIST/cursor/lazyeng.mdc;               MODE=owned;  _p=.cursor/rules/lazyeng.mdc ;;
        windsurf)            SRC=$DIST/windsurf/lazyeng.md;              MODE=owned;  _p=.windsurf/rules/lazyeng.md ;;
        cline)               SRC=$DIST/cline/lazyeng.md;                 MODE=owned;  _p=.clinerules/lazyeng.md ;;
        claude-skill)        SRC=$DIST/skills/lazyeng/SKILL.md;          MODE=owned;  _p=.claude/skills/lazyeng/SKILL.md ;;
        *) return 1 ;;
    esac

    if [ "$_s" = global ]; then
        # Only where the tool documents a global instruction file.
        case $_t in
            claude)              _p=.claude/CLAUDE.md ;;
            claude-skill)        _p=.claude/skills/lazyeng/SKILL.md ;;
            gemini)              _p=.gemini/GEMINI.md ;;
            agents)              _p=.gemini/AGENTS.md ;;          # Antigravity/Gemini CLI global
            windsurf)            _p=.codeium/windsurf/memories/global_rules.md ;;
            junie)               _p=.junie/AGENTS.md ;;
            opencode)            _p=.config/opencode/AGENTS.md ;;
            *) return 1 ;;
        esac
        DEST=$HOME/$_p
    else
        DEST=$BASE/$_p
    fi
    return 0
}

# Remove a previously installed marker block from a file on stdin.
strip_block() {
    awk -v b="$BEGIN_MARK" -v e="$END_MARK" '
        $0 == b { skip = 1; next }
        $0 == e { skip = 0; next }
        !skip   { print }
    '
}

# Drop trailing blank lines from stdin.
trim_trailing() {
    awk '{ l[NR] = $0 }
         END { n = NR; while (n > 0 && l[n] ~ /^[[:space:]]*$/) n--
               for (i = 1; i <= n; i++) print l[i] }'
}

# Block to embed: the generated file minus its banner line, wrapped in markers.
make_block() {
    printf '%s\n' "$BEGIN_MARK"
    tail -n +2 "$1"
    printf '%s\n' "$END_MARK"
}

ensure_dist() {
    [ -f "$DIST/AGENTS.md" ] || "$ROOT/build.sh" >/dev/null || die "build failed; run ./build.sh"
}

do_shared_install() {
    dest=$1; src=$2
    tmp=$(mktemp) || die "mktemp failed"
    trap 'rm -f "$tmp" "$tmp2"' EXIT
    tmp2=$(mktemp) || die "mktemp failed"

    if [ -f "$dest" ]; then
        strip_block < "$dest" | trim_trailing > "$tmp"
    else
        : > "$tmp"
    fi

    {
        if [ -s "$tmp" ]; then cat "$tmp"; printf '\n\n'; fi
        make_block "$src"
    } > "$tmp2"

    if [ -f "$dest" ] && cmp -s "$tmp2" "$dest"; then
        say "up to date: $dest"
        return 0
    fi
    if [ "$DRY" = 1 ]; then
        act "write $dest"
        return 0
    fi
    mkdir -p "$(dirname "$dest")"
    cat "$tmp2" > "$dest"
    say "installed: $dest"
}

do_owned_install() {
    dest=$1; src=$2
    if [ -f "$dest" ] && ! grep -qF "$OWNED_MARK" "$dest" && [ "$FORCE" != 1 ]; then
        die "$dest exists and was not created by LazyEng; re-run with --force to overwrite"
    fi
    if [ -f "$dest" ] && cmp -s "$src" "$dest"; then
        say "up to date: $dest"
        return 0
    fi
    if [ "$DRY" = 1 ]; then
        act "write $dest"
        return 0
    fi
    mkdir -p "$(dirname "$dest")"
    cp "$src" "$dest"
    say "installed: $dest"
}

do_shared_uninstall() {
    dest=$1
    [ -f "$dest" ] || { say "not installed: $dest"; return 0; }
    if ! grep -qF "$BEGIN_MARK" "$dest"; then
        say "not managed by LazyEng, leaving alone: $dest"
        return 0
    fi
    if [ "$DRY" = 1 ]; then act "clean $dest"; return 0; fi
    tmp=$(mktemp) || die "mktemp failed"
    trap 'rm -f "$tmp"' EXIT
    strip_block < "$dest" | trim_trailing > "$tmp"
    if [ -s "$tmp" ]; then
        cat "$tmp" > "$dest"
        say "removed LazyEng block from: $dest"
    else
        rm -f "$dest"
        say "removed: $dest"
    fi
}

do_owned_uninstall() {
    dest=$1
    [ -f "$dest" ] || { say "not installed: $dest"; return 0; }
    if ! grep -qF "$OWNED_MARK" "$dest"; then
        say "not managed by LazyEng, leaving alone: $dest"
        return 0
    fi
    if [ "$DRY" = 1 ]; then act "remove $dest"; return 0; fi
    rm -f "$dest"
    say "removed: $dest"
}

if [ "$LIST" = 1 ]; then
    say "target          project scope / global scope"
    say "--------------  ---------------------------------------------------------------"
    for t in agents claude claude-skill gemini copilot copilot-instructions junie amazonq cursor windsurf cline aider; do
        line=$(describe "$t")
        if resolve "$t" global 2>/dev/null; then
            g=$DEST
            say "$(printf '%-15s' "$t") $line"
            say "$(printf '%-15s' '') global: ${g/#$HOME/~}"
        else
            say "$(printf '%-15s' "$t") $line"
            say "$(printf '%-15s' '') global: not supported — install per project"
        fi
    done
    exit 0
fi

ensure_dist

if [ "$SCOPE" = global ]; then
    BASE=$HOME
else
    mkdir -p "$DIR" 2>/dev/null || true
    BASE=$(cd "$DIR" 2>/dev/null && pwd) || die "no such directory: $DIR"
fi

if [ "$TARGET" = all ]; then
    if [ "$SCOPE" = global ]; then
        usage_error "--target all only works with --scope project; name global targets explicitly"
    fi
    ALL="agents claude gemini copilot copilot-instructions junie amazonq cursor windsurf cline aider"
else
    ALL=$TARGET
fi

fail=0
for t in $ALL; do
    describe "$t" >/dev/null || usage_error "unknown target: $t (see --list)"
    if ! resolve "$t" "$SCOPE"; then
        if [ "$SCOPE" = global ]; then
            say "skip $t: no documented global instruction file; install per project"
            continue
        fi
        usage_error "unknown target: $t"
    fi
    if [ "$UNINSTALL" = 1 ]; then
        if [ "$MODE" = shared ]; then do_shared_uninstall "$DEST"; else do_owned_uninstall "$DEST"; fi
    else
        if [ "$MODE" = shared ]; then do_shared_install "$DEST" "$SRC"; else do_owned_install "$DEST" "$SRC"; fi
    fi || fail=1
done

[ "$fail" = 0 ] || die "one or more targets failed"
[ "$DRY" = 0 ] || say "(dry run — nothing written)"
